def dump(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def text(value: Any) -> str:
    if value is None:
        return '未记录'
    if isinstance(value, bool):
        return '是' if value else '否'
    if isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def esc(value: Any) -> str:
    return html.escape(text(value), quote=True)


def fence(value: Any, language='json') -> str:
    body = value if isinstance(value, str) else dump(value)
    longest = max((len(match[0]) for match in re.finditer(r'`+', body)), default=0)
    ticks = '`' * max(3, longest + 1)
    return f'{ticks}{language}\n{body}\n{ticks}\n'


def md_cell(value: Any) -> str:
    return text(value).replace('|', '\\|').replace('\n', ' / ')


def md_table(headers, rows) -> str:
    if not rows:
        return '未记录。\n'
    lines = ['| ' + ' | '.join(map(md_cell, headers)) + ' |',
             '| ' + ' | '.join('---' for _ in headers) + ' |']
    lines.extend('| ' + ' | '.join(map(md_cell, row)) + ' |' for row in rows)
    return '\n'.join(lines) + '\n'


def html_table(headers, rows) -> str:
    if not rows:
        return '<p class="muted">未记录。</p>'
    return '<div class="scroll"><table><thead><tr>' + ''.join('<th>' + esc(x) + '</th>' for x in headers) + '</tr></thead><tbody>' + ''.join(
        '<tr>' + ''.join('<td>' + esc(x) + '</td>' for x in row) + '</tr>' for row in rows) + '</tbody></table></div>'


def href(path: Path, from_directory: Path) -> str:
    return quote(Path(os.path.relpath(path, from_directory)).as_posix(), safe='/')


def numeric(value):
    return value if isinstance(value, (int, float)) and not isinstance(value, bool) else None


def usage_values(call):
    usage = call.get('usage') or {}
    details = usage.get('prompt_tokens_details') or usage.get('input_tokens_details') or {}
    input_tokens = numeric(usage.get('prompt_tokens', usage.get('input_tokens')))
    output_tokens = numeric(usage.get('completion_tokens', usage.get('output_tokens')))
    total_tokens = numeric(usage.get('total_tokens'))
    if total_tokens is None and input_tokens is not None and output_tokens is not None:
        total_tokens = input_tokens + output_tokens
    return input_tokens, output_tokens, total_tokens, numeric(details.get('cached_tokens', usage.get('cache_read_input_tokens')))


class Sections:
    def __init__(self):
        self.markdown, self.html = [], []

    def add(self, title, *, note=None, headers=None, rows=None, value=None, language='json', folded=False):
        md = f'## {title}\n\n'
        body = '<h2>' + esc(title) + '</h2>'
        if note:
            md += str(note) + '\n\n'
            body += '<p>' + esc(note) + '</p>'
        if headers is not None:
            md += md_table(headers, rows or []) + '\n'
            body += html_table(headers, rows or [])
        if value is not None:
            md += fence(value, language) + '\n'
            code = '<pre>' + esc(value if isinstance(value, str) else dump(value)) + '</pre>'
            body += '<details><summary>展开原始记录</summary>' + code + '</details>' if folded else code
        self.markdown.append(md)
        self.html.append('<section>' + body + '</section>')


def task_report(case: int, source: Path, record: dict, ledger_item: dict | None = None,
                adjudication: dict | None = None):
    response = record.get('response') if isinstance(record.get('response'), dict) else {}
    request = record.get('request') if isinstance(record.get('request'), dict) else {}
    ledger_item = ledger_item or {}
    task_id = response.get('task_id')
    adjudication = adjudication if adjudication and adjudication.get('task_id') == task_id else {}
    safe_id = re.sub(r'[^A-Za-z0-9_-]', '_', str(task_id or 'missing'))
    query = request.get('query') or ledger_item.get('query') or '原问题未记录'
    query_origin = '实际请求原文' if request.get('query') else '台账计划问题；实际请求原文未保存'
    scenario = ledger_item.get('scenario') or record.get('scenario') or SCENARIOS.get(case, '未记录场景')
    datasource = response.get('datasource_id') or (request.get('workspace') or {}).get('datasource_id')
    budget = response.get('budget') if isinstance(response.get('budget'), dict) else {}
    calls = budget.get('model_usage') or []
    events = budget.get('events') or []
    logs = response.get('execution_log') or []
    actions = response.get('plan') or []
    evidence = response.get('evidence') or []
    sections = Sections()
    sections.add('1. 任务与记录边界', note='系统状态、SQL成功和模型审核均不等于业务验收通过。外部数字核算与业务判定由独立主报告给出；本文不回写或修饰原任务。',
                 headers=['项目', '记录'], rows=[['场景', scenario], ['问题来源', query_origin], ['任务编号', task_id], ['数据源', datasource],
                     ['HTTP状态', record.get('http_status')], ['系统状态', response.get('status')],
                     ['最终审核完成', response.get('final_reviewed')], ['可恢复标记', response.get('resumable')],
                     ['墙钟秒数', record.get('elapsed_seconds')], ['累计主动秒数', budget.get('active_seconds')],
                     ['停止原因', response.get('stop_reason')], ['原始JSON SHA256', hashlib.sha256(source.read_bytes()).hexdigest()]])
    if adjudication:
        sections.add('独立业务判定（开发核查，不改写系统状态）',
                     note=str(adjudication.get('verdict')) + '：' + str(adjudication.get('reason')))
    sections.add('用户原问题', value=query, language='text')
    sections.add('任务理解与绑定条件', value={key: response.get(key) for key in (
        'standalone_query', 'required_questions', 'requirements', 'scenario', 'selected_semantics', 'route_reason', 'clarification')}, folded=True)

    sections.add('2. 实际行动记录', note='此表包含成功、失败、阻塞、未执行和复用；attempts缺失时不推断尝试次数。',
                 headers=['行动ID', '类型', '目的', '状态', '尝试数', '输入依赖', '结果编号', '错误'],
                 rows=[[a.get('id'), a.get('action_type', a.get('kind')), a.get('goal'), a.get('status'),
                        a.get('attempts'), a.get('input_result_ids'), a.get('result_ids'), a.get('error')] for a in actions])
    for action in actions:
        identity = action.get('id')
        history = [entry for entry in logs if entry.get('stage') in {'query_action', 'react_action'}
                   and entry.get('id', entry.get('action_id')) == identity]
        repairs = [entry for entry in events if entry.get('step_id') == identity
                   and (entry.get('stage') == 'repair' or entry.get('event') == 'repair')]
        related = [entry for entry in evidence if entry.get('step_id') == identity]
        sections.add('行动 ' + text(identity) + '：候选、校验及局部修复',
                     note='SQL是否执行以行动状态和实际工具记录为准；此处保留已有候选快照，未保存的旧候选不补造。',
                     value={'current_action': action, 'attempt_snapshots': history, 'repair_events': repairs,
                            'result_contracts': [{'result_id': item.get('id'), 'query_contract': item.get('query_contract')} for item in related]}, folded=True)

    sections.add('3. 证据目录', headers=['结果ID', '行动', '来源', '输入依赖', '检查状态', '完整', '总行数', '已存行数', '本报告预览行数'],
                 rows=[[e.get('id'), e.get('step_id'), e.get('datasource_id'), e.get('input_result_ids'),
                        e.get('check_status'), e.get('complete'), e.get('total_rows'), e.get('stored_rows'), len(e.get('rows') or [])] for e in evidence],
                 note='rows仅展示原始响应中实际保存的预览。完整标志针对后台结果，不代表本报告预览覆盖全集；未知总行数保留未知，空结果不解释成零。')
    for item in evidence:
        metadata = {key: value for key, value in item.items() if key != 'rows'}
        sections.add('证据 ' + text(item.get('id')) + '：元信息与数值预览',
                     value={'metadata': metadata, 'saved_preview_rows': item.get('rows') or [],
                            'preview_only': True}, folded=True)

    decisions = [entry for entry in logs if entry.get('stage') == 'react_decision']
    sections.add('4. 每轮调查进度与下一动作', note='只记录可观察的行动理由、结构化进度和动作输出，不展示或推测模型内部思维链。没有progress_update时明确保留缺失。',
                 headers=['轮次', '任务修订', '行动类型', '行动理由'],
                 rows=[[index, entry.get('revision'), (entry.get('action') or {}).get('type'), entry.get('action_reason')]
                       for index, entry in enumerate(decisions, 1)])
    for index, entry in enumerate(decisions, 1):
        sections.add(f'第{index}轮：原始进度更新与动作', value={key: entry.get(key) for key in (
            'revision', 'action_reason', 'progress_update', 'action')}, folded=True)

    sections.add('5. 逐次模型调用与用量', note='重试分别列出；未报告用量不按零计算。UTF-8字节量是保守估算，不是各区块实际token；接口usage是整次实际总量。缓存命中是输入子集，不重复相加。',
                 headers=['序号', '接口', '节点／行动', '模型', '尝试', '状态', '输入token', '输出token', '总token', '缓存token', '请求字符', '秒数'],
                 rows=[[index, call.get('kind'), str(call.get('node')) + ' / ' + str(call.get('step_id')),
                        call.get('model'), call.get('attempt'), call.get('status'), *usage_values(call),
                        call.get('request_characters'), call.get('elapsed_seconds')] for index, call in enumerate(calls, 1)])
    for index, call in enumerate(calls, 1):
        sections.add(f'调用{index}：输入区块与供应商用量原记录', value=call, folded=True)
    if not calls:
        sections.add('模型调用记录缺失', note='此响应没有逐次model_usage。不能据此声称没有调用模型；也不从调用总数补造分项token或耗时。')

    tools = [event for event in events if event.get('stage') == 'tool_dispatch' or event.get('event') == 'tool']
    sections.add('6. 工具调用', headers=['记录序号', '工具次序', '工具', '行动', '主动秒数'],
                 rows=[[e.get('sequence'), e.get('index'), e.get('name'), e.get('step_id'), e.get('active_seconds')] for e in tools],
                 note=f"预算账本记载工具次数：{text(budget.get('tools'))}；工具上限：{text(budget.get('tool_limit'))}。本表仅列实际保存的事件，不从空缺补造工具调用。")
    skills = [event for event in events if event.get('stage') in {'skill_loaded', 'skill_injection'}]
    sections.add('Skill读取与实际注入', headers=['序号', '事件', 'Skill', '节点／行动', '字符数', '版本／指纹', '主动秒数'],
                 rows=[[e.get('sequence'), e.get('stage'), e.get('skill'),
                        text(e.get('node')) + ' / ' + text(e.get('step_id')), e.get('characters'),
                        e.get('version', e.get('content_sha256')), e.get('active_seconds')] for e in skills],
                 note='最终加载清单：' + text(response.get('selected_skills')) + '。选中、实际读取和每节点注入分别看待；没有事件不推断已注入。')
    sections.add('7. 预算与停止', value={key: value for key, value in budget.items() if key not in {'model_usage', 'events'}}, folded=True)
    reviews = response.get('reviews') or []
    sections.add('8. 最终Reviewer原始记录', note='记录缺失时不从系统状态反推已审核。此处是实际保存的审核意见，独立业务验收可能仍不通过。', value=reviews, folded=True)
    sections.add('审核定稿／实际交付文本', note='最终审核完成标志：' + text(response.get('final_reviewed')) + '。以下原文不再调用模型改写；未审核时只表示实际交付内容。',
                 value=response.get('analysis') or response.get('message') or '未记录交付文本', language='markdown')
    sections.add('9. 完整执行与审计事件附录', value={'execution_log': logs, 'budget_events': events}, folded=True)
    sections.add('10. 来源与缺失边界', note='运行轨迹依据保存的响应生成；如有独立业务判定则单独标明，不把评测结论写回任务或运行知识。不读取私有答案。未单独保存的草稿、完整提示词、模型内部推理、服务端绝对起止时刻和供应商实扣金额不补造。',
                 value={'source_file': str(source.resolve()), 'record_source_kind': record.get('source_kind'),
                        'ledger_status': ledger_item.get('status'), 'request': request}, folded=True)
    summary = {'case': case, 'task_id': task_id, 'query': query, 'scenario': scenario,
               'datasource_id': datasource, 'status': response.get('status'),
               'final_reviewed': response.get('final_reviewed'), 'elapsed_seconds': record.get('elapsed_seconds'),
               'active_seconds': budget.get('active_seconds'), 'tools': budget.get('tools'),
               'model_call_count': len(calls) if calls else None, 'model_calls': budget.get('model_calls'),
               'stop_reason': response.get('stop_reason'),
               'business_verdict': (str(adjudication.get('verdict')) + '：' + str(adjudication.get('reason'))
                                    if adjudication else '由独立主报告核验，本文不判定通过')}
    title = f'ReAct V1 场景{case}过程报告：{text(task_id)}'
    markdown = MARKER + '\n\n# ' + title + '\n\n[原始运行 JSON](<' + str(source.resolve()) + '>)\n\n' + '\n'.join(sections.markdown)
    return safe_id, title, markdown, '\n'.join(sections.html), summary


def build_reports(directory: Path = DIRECTORY, docs_directory: Path = DOCS) -> dict[str, Any]:
    """Build only from present records; explicit paths also allow temp fixtures."""
    directory, docs_directory = Path(directory).resolve(), Path(docs_directory).resolve()
    output = directory / 'process_reports'
    for folder in (output / 'tasks', output / 'markdown', docs_directory):
        folder.mkdir(parents=True, exist_ok=True)
    ledger_path = directory / 'paid_runs.json'
    ledger = json.loads(ledger_path.read_text()) if ledger_path.exists() else {}
    adjudication_path = directory / 'business_adjudication.json'
    adjudications = json.loads(adjudication_path.read_text()).get('runs', []) if adjudication_path.exists() else []
    ledger_items = {item.get('case'): dict(item) for item in ledger.get('questions', [])}
    for item in ledger.get('runs', []):
        ledger_items[item.get('case')] = {**ledger_items.get(item.get('case'), {}), **item}
    summaries, cards, missing = [], [], []
    for case in (1, 2, 3):
        source = directory / f'case_{case}.json'
        if not source.exists():
            item = ledger_items.get(case, {})
            missing.append({'case': case, 'query': item.get('query'), 'ledger_status': item.get('status'), 'output_present': False})
            cards.append('<article><h2>场景' + str(case) + ' · ' + esc(SCENARIOS[case]) + '</h2><p>计划问题：' + esc(item.get('query')) + '</p><p class="warning">尚无保存的case响应；台账状态：' + esc(item.get('status')) + '。不推断已执行或通过。</p></article>')
            continue
        record = json.loads(source.read_text())
        judgement = next((item for item in adjudications if item.get('case') == case), None)
        safe_id, title, markdown, body, summary = task_report(case, source, record, ledger_items.get(case), judgement)
        stem = f'case_{case}_{safe_id}'
        report_md = docs_directory / f'react_v1_{stem}.md'
        if report_md.exists() and not report_md.read_text().startswith(MARKER):
            raise RuntimeError('拒绝覆盖非本脚本生成的文档：' + str(report_md))
        report_md.write_text(markdown, encoding='utf-8')
        (output / 'markdown' / f'{stem}.md').write_text(markdown, encoding='utf-8')
        task_html = output / 'tasks' / f'{stem}.html'
        links = '<p class="links"><a href="../index.html">返回索引</a><a href="' + href(report_md, task_html.parent) + '">Markdown</a><a href="' + href(source, task_html.parent) + '">原始JSON</a></p>'
        page = '<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>' + esc(title) + '</title><style>' + CSS + '</style><body><header><h1>' + esc(title) + '</h1>' + links + '</header>' + body + '</body></html>'
        task_html.write_text(page, encoding='utf-8')
        summaries.append({**summary, 'source': str(source), 'markdown': str(report_md), 'html': str(task_html)})
        cards.append('<article><h2>场景' + str(case) + ' · ' + esc(summary['scenario']) + '</h2><p>' + esc(summary['query']) + '</p><p><span class="pill">系统 ' + esc(summary['status']) + '</span>　最终审核：' + esc(summary['final_reviewed']) + '　主动处理：' + esc(summary['active_seconds']) + '秒　工具：' + esc(summary['tools']) + '</p><p class="muted">' + esc(summary['business_verdict']) + '</p><p class="links"><a href="' + href(task_html, output) + '">完整过程</a><a href="' + href(report_md, output) + '">Markdown</a><a href="' + href(source, output) + '">原始JSON</a></p></article>')
    index = '<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>ReAct V1 三场景过程报告</title><style>' + CSS + '</style><body><header><h1>ReAct V1 · 三场景过程报告</h1><p>从已有运行JSON离线生成，零新增模型、API和查询。</p><p class="warning">系统completed、SQL成功或Reviewer放行，均不能直接认定业务验收通过。数字和解释以独立主报告的核验为准。</p></header>' + ''.join(cards) + '</body></html>'
    (output / 'index.html').write_text(index, encoding='utf-8')
    manifest = {'reported_cases': len(summaries), 'expected_cases': 3, 'runs': summaries,
                'missing_records': missing, 'new_model_calls': 0, 'new_http_calls': 0, 'new_sql_calls': 0,
                'index': str(output / 'index.html')}
    (output / 'summary.json').write_text(dump(manifest) + '\n', encoding='utf-8')
    return manifest


if __name__ == '__main__':
    result = build_reports()
    print(json.dumps({key: result[key] for key in ('reported_cases', 'expected_cases', 'missing_records', 'index', 'new_model_calls')}, ensure_ascii=False))
